package jp.ecuacion.splib.web.util.internal;

import java.lang.reflect.Field;
import jp.ecuacion.lib.core.annotation.ItemNameKeyClass;
import jp.ecuacion.splib.core.audit.AuditLogUtil;
import jp.ecuacion.splib.core.audit.AuditLogWriter.TargetData;
import jp.ecuacion.splib.core.record.SplibRecord;
import jp.ecuacion.splib.web.form.SplibGeneralForm;
import org.apache.commons.lang3.StringUtils;
import org.jspecify.annotations.Nullable;

/**
 * Adds the data the forms of a request are about to the audit log record of the current
 * operation, so that applications need not call {@link AuditLogUtil#addTarget} for the screens
 * {@code ecuacion-splib-web} provides.
 *
 * <p>The data is taken from each root record of the forms: its own primary key, the first
 *     segment of {@link SplibRecord#getIds()} (the record the edit page shows, or the row whose
 *     button was pressed on the list page), and its kind, the {@link ItemNameKeyClass} value of
 *     the record class or its superclass capitalized ({@code "acc"} to {@code "Acc"}), which is
 *     the entity name for records generated by {@code ecuacion-tool-code-generator}. A record
 *     with no ID (a new one, a search condition) or without {@link ItemNameKeyClass} is
 *     skipped. Related records' primary keys in {@code ids} are not added, since the operation
 *     only refers to them.</p>
 */
public class AuditLogTargetUtil {

  private AuditLogTargetUtil() {}

  /**
   * Adds the data the root records of {@code forms} are about. Does nothing when the current
   * operation is not recorded.
   *
   * @param forms the forms
   */
  public static void addTargetsOf(SplibGeneralForm... forms) {
    for (SplibGeneralForm form : forms) {
      for (Field field : form.getRootRecordFields()) {
        if (form.getRootRecord(field.getName()) instanceof SplibRecord rec) {
          TargetData target = targetOf(rec);
          if (target != null) {
            AuditLogUtil.addTarget(target.type(), target.id());
          }
        }
      }
    }
  }

  /**
   * Returns the data {@code rec} is about, {@code null} if it has no ID or no kind.
   */
  static @Nullable TargetData targetOf(SplibRecord rec) {
    // The first ","-separated segment is the record's own primary key (see SplibRecord#getIds()).
    String id = rec.getIds().split(",", -1)[0];
    if (id.isEmpty()) {
      return null;
    }

    // ItemNameKeyClass is not @Inherited, and is put on the generated base record class.
    for (Class<?> cls = rec.getClass(); cls != null; cls = cls.getSuperclass()) {
      ItemNameKeyClass annotation = cls.getDeclaredAnnotation(ItemNameKeyClass.class);
      if (annotation != null) {
        return new TargetData(StringUtils.capitalize(annotation.value()), id);
      }
    }

    return null;
  }
}
