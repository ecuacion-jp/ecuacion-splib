package jp.ecuacion.splib.web.oauth2;

import java.util.Objects;
import org.jspecify.annotations.Nullable;
import org.springframework.security.oauth2.client.endpoint.DefaultOAuth2TokenRequestParametersConverter;
import org.springframework.security.oauth2.client.endpoint.OAuth2AuthorizationCodeGrantRequest;
import org.springframework.util.MultiValueMap;

/**
 * Builds the parameters of token requests,
 *     replacing {@code client_secret} with the JWT generated by
 *     {@link SplibAppleClientSecretService} for requests sent to Apple.
 *
 * <p>The parameters are built by Spring Security's
 *     {@link DefaultOAuth2TokenRequestParametersConverter} first.
 *     With {@code client_secret_post} it already contains {@code client_secret}
 *     (empty, since the app doesn't set Apple's {@code client-secret}),
 *     so the JWT must replace it, not be added to it.
 *     Apple rejects the request with {@code invalid_client} when two are sent.</p>
 *
 * <p>Apple is detected by the host of the token endpoint, not by the registrationId.</p>
 *
 * <p>Pass {@link #convert(OAuth2AuthorizationCodeGrantRequest)} to
 *     {@code setParametersConverter} of the token response client.</p>
 */
public class SplibOauth2TokenRequestParametersConverter {

  private final DefaultOAuth2TokenRequestParametersConverter<
      OAuth2AuthorizationCodeGrantRequest> defaultConverter =
          new DefaultOAuth2TokenRequestParametersConverter<>();

  @Nullable
  private final SplibAppleClientSecretService appleClientSecretService;

  /**
   * Constructs a new instance.
   *
   * @param appleClientSecretService appleClientSecretService, may be {@code null} when Apple
   *     login is not configured
   */
  public SplibOauth2TokenRequestParametersConverter(
      @Nullable SplibAppleClientSecretService appleClientSecretService) {
    this.appleClientSecretService = appleClientSecretService;
  }

  /**
   * Builds the parameters of the token request.
   *
   * @param grantRequest grantRequest
   * @return parameters of the token request
   */
  public MultiValueMap<String, String> convert(OAuth2AuthorizationCodeGrantRequest grantRequest) {
    MultiValueMap<String, String> params =
        Objects.requireNonNull(defaultConverter.convert(grantRequest));

    SplibAppleClientSecretService appleService = appleClientSecretService;
    if (appleService != null && SplibAppleEndpoints
        .isApple(grantRequest.getClientRegistration().getProviderDetails().getTokenUri())) {
      params.set("client_secret", appleService.generateClientSecret());
    }

    return params;
  }
}
